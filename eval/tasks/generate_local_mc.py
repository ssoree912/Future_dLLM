def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for stale in OUT.glob("*"):
        stale.unlink()

    (OUT / "_local_mc_mmlu_yaml").write_text(MMLU_TEMPLATE)
    categories: list[str] = []
    for subject, category in SUBJECTS.items():
        if category not in categories:
            categories.append(category)
        (OUT / f"local_mc_mmlu_{subject}.yaml").write_text(
            MMLU_SUBJECT.format(subject=subject, alias=subject.replace("_", " "),
                                category=category))
    for category in categories:
        (OUT / f"_local_mc_mmlu_{category}.yaml").write_text(
            MMLU_CATEGORY.format(category=category, alias=category.replace("_", " ")))
    (OUT / "_local_mc_mmlu.yaml").write_text(MMLU_GROUP.format(
        tasks="\n".join(f"  - local_mc_mmlu_{c}" for c in categories)))

    (OUT / "local_mc_arc_challenge.yaml").write_text(ARC)
    (OUT / "local_mc_piqa.yaml").write_text(PIQA)
    (OUT / "local_mc_gpqa_main_n_shot.yaml").write_text(GPQA)
    print(f"wrote {len(list(OUT.glob('*')))} files to {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
