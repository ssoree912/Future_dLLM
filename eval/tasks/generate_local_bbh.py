#!/usr/bin/env python
"""Write local_bbh/ — lm-eval's own BBH tasks, reading local parquet.

``--tasks bbh`` in lm-eval 0.4.x resolves to the **CoT few-shot** group
(tasks/bbh/cot_fewshot), which is what dLLM-cache's BBH scripts run. Those
configs pull SaylorTwift/bbh from the Hub; these copies keep the prompt, the
three hand-written CoT exemplars, the ``the answer is`` regex filter and the
metric byte-identical, and only swap the data source, so a run needs nothing
but ``scripts/download_data.py --parts bbh``.

Copying rather than hand-writing matters here: each of the 27 tasks carries its
own three CoT exemplars, hundreds of lines in total, and a paraphrase would
silently stop being the benchmark everyone else reports.

``DATA_DIR`` is substituted by ``scripts/run_eval.sh`` at run time.
"""

from __future__ import annotations

import shutil
from pathlib import Path

import yaml

import lm_eval

SRC = Path(lm_eval.__file__).resolve().parent / "tasks" / "bbh" / "cot_fewshot"
OUT = Path(__file__).resolve().parent / "local_bbh"
TEMPLATE = "_local_bbh_template_yaml"


def main() -> int:
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    # The shared template holds dataset_path; each task adds its own data_files,
    # because one parquet per BBH task is how download_data.py writes them.
    template = yaml.safe_load((SRC / "_cot_fewshot_template_yaml").read_text())
    template["dataset_path"] = "parquet"
    (OUT / TEMPLATE).write_text(
        "# Generated by generate_local_bbh.py — lm-eval bbh/cot_fewshot/"
        "_cot_fewshot_template_yaml,\n# with the Hub dataset swapped for local parquet.\n"
        + yaml.safe_dump(template, sort_keys=False, allow_unicode=True))

    group = yaml.safe_load((SRC / "_bbh.yaml").read_text())
    tasks = []
    for upstream in group["task"]:
        name = upstream.removeprefix("bbh_cot_fewshot_")
        cfg = yaml.safe_load((SRC / f"{name}.yaml").read_text())
        cfg.pop("dataset_name", None)          # one file per task, not one config
        cfg["dataset_kwargs"] = {"data_files": {"test": f"DATA_DIR/eval/bbh/{name}.parquet"}}
        cfg["include"] = TEMPLATE
        cfg["task"] = f"local_bbh_{name}"
        tasks.append(cfg["task"])
        (OUT / f"{name}.yaml").write_text(
            f"# Generated by generate_local_bbh.py — lm-eval bbh/cot_fewshot/{name}.yaml,\n"
            "# with the Hub dataset swapped for local parquet.\n"
            + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True))

    group["group"] = "local_bbh"
    group["task"] = tasks
    (OUT / "_local_bbh.yaml").write_text(
        "# Generated by generate_local_bbh.py — lm-eval bbh/cot_fewshot/_bbh.yaml.\n"
        + yaml.safe_dump(group, sort_keys=False, allow_unicode=True))

    print(f"{len(tasks)} tasks + template + group -> {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
